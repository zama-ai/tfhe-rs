// Bits (msb) 0123 (lsb) in u4
static LUT_EXOR_TO_0: [[u8; 1 << 4]; 4] = build_lut_exor(0);
static LUT_EXOR_TO_1: [[u8; 1 << 4]; 4] = build_lut_exor(1);
static LUT_EXOR_TO_2: [[u8; 1 << 4]; 4] = build_lut_exor(2);
static LUT_EXOR_TO_3: [[u8; 1 << 4]; 4] = build_lut_exor(3);
#[rustfmt::skip]
pub static LUT_EXOR_FW: [&[[u8; 1 << 4]; 4]; 2] = [
    &LUT_EXOR_TO_3, &LUT_EXOR_TO_2,
];
#[rustfmt::skip]
pub static LUT_EXOR_BW: [&[[u8; 1 << 4]; 4]; 4] = [
    &LUT_EXOR_TO_3, &LUT_EXOR_TO_2, &LUT_EXOR_TO_1, &LUT_EXOR_TO_0,
];

// e-xor(b) = xor of all bits except b. [Ex: e-xor(1010,0) = 0, e-xor(1010,1) = 1.]
// Bits (msb) 0123 (lsb) in u4 [more convenient for describing the M-layer?]
const fn u4_exor(x: u8, b: u8) -> u8 {
    assert!(b < 4 && x < 16);

    let excluded_bit_mask: u8 = 1 << (3 - b);

    let kept_bits: u8 = x & !excluded_bit_mask;

    // xor the 4 kept bits together by folding the width in half, twice
    let folded_to_2_bits: u8 = (kept_bits & 0x3) ^ (kept_bits >> 2);

    (folded_to_2_bits & 0x1) ^ (folded_to_2_bits >> 1)
}

// e-xor(b) = xor of all bits except b. [Ex: e-xor(1010,0) = 0, e-xor(1010,1) = 1.]
// Bits (msb) 0123 (lsb) in u4 [more convenient for describing the M-layer?]
const fn build_lut_exor(to_bit: u8) -> [[u8; 1 << 4]; 4] {
    let mut lut_exor_to_b: [[u8; 1 << 4]; 4] = [[0; 1 << 4]; 4];
    let mut b: usize = 0;

    while b < 4 {
        // for loop not allowed in const fn
        let mut x: usize = 0;
        while x < (1 << 4) {
            let exor_bit: u8 = u4_exor(x as u8, b as u8);

            lut_exor_to_b[b][x] = exor_bit << to_bit;
            x += 1;
        }
        b += 1;
    }
    lut_exor_to_b
}

/* LUTs for xoring to high / low bits ---------------------------------------------- */
// [Nb] Probably overkill in this case
pub static LUT_XOR_TO_LOW: [u8; 1 << 4] = [
    // (01) ^ (23): (x & 3) ^^ (x >> 2) for x in range(16)
    0x0, 0x1, 0x2, 0x3, 0x1, 0x0, 0x3, 0x2, 0x2, 0x3, 0x0, 0x1, 0x3, 0x2, 0x1, 0x0,
];
static LUT_XOR_TO_HIGH: [u8; 1 << 4] = [
    // <above> << 2
    0x0, 0x4, 0x8, 0xc, 0x4, 0x0, 0xc, 0x8, 0x8, 0xc, 0x0, 0x4, 0xc, 0x8, 0x4, 0x0,
];
pub static LUT_XOR_FW: [[u8; 1 << 4]; 2] = [LUT_XOR_TO_HIGH, LUT_XOR_TO_LOW];

// xoring + extract bits (low/high of 2 output bits)
pub static LUT_XOR_BIT_LOW: [[u8; 1 << 4]; 4] = build_lut_xor_bit(0);
pub static LUT_XOR_BIT_HIGH: [[u8; 1 << 4]; 4] = build_lut_xor_bit(1);

const fn build_lut_xor_bit(selected_xor_bit: u8) -> [[u8; 1 << 4]; 4] {
    let mut lut_xor_bit_to_b: [[u8; 1 << 4]; 4] = [[0; 1 << 4]; 4];
    let mut b: usize = 0;

    while b < 4 {
        let out_shift: u8 = 3 - (b as u8);

        // for loop not allowed in const fn
        let mut x: usize = 0;
        while x < (1 << 4) {
            let xor_u2: u8 = LUT_XOR_TO_LOW[x];
            let extracted_bit: u8 = (xor_u2 >> selected_xor_bit) & 0x1;

            lut_xor_bit_to_b[b][x] = extracted_bit << out_shift;
            x += 1;
        }
        b += 1;
    }
    lut_xor_bit_to_b
}


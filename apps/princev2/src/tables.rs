// Build special LUTs: SBox( x ^ inner ) ^ outer, depending on nibble index
const fn build_lut_xor_sbox_xor(
    sbox: [u8; 1 << 4],
    xor_inner: [u8; 64 / 4],
    xor_outer: [u8; 64 / 4],
) -> [[u8; 1 << 4]; 64 / 4] {
    let mut lut_xor_sbox_xor: [[u8; 1 << 4]; 64 / 4] = [[0; 1 << 4]; 64 / 4];
    let mut nibble: usize = 0;
    while nibble < 64 / 4 {
        // for loop not allowed in const fn
        let mut x: usize = 0;
        while x < (1 << 4) {
            let sbox_in: u8 = (x as u8) ^ xor_inner[nibble];
            let sbox_out: u8 = sbox[sbox_in as usize];

            lut_xor_sbox_xor[nibble][x] = sbox_out ^ xor_outer[nibble];
            x += 1;
        }
        nibble += 1;
    }
    lut_xor_sbox_xor
}


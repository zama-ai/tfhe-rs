use rayon::prelude::*;
const VAR_POS_WEIGHT: usize = 10;

pub struct HpuCluster {
    nodes: HashMap<u8, HpuNodeWrapped>,
    workload: Arc<[atomic::AtomicUsize; MAX_HPU_IN_CLUSTER]>,
    iop_id: Arc<atomic::AtomicU8>,
    pub(crate) cmd_tx: mpsc::Sender<Arc<cmd::HpuCmd>>,
    params: Arc<HpuParameters>,
    fw_sig: Arc<HashMap<(StaticIOp, u16), IOpSig>>,
    dyn_fw_sig: Arc<Mutex<HashMap<IOpcode, IOpSig>>>,

    // Keep track of polling threads
    bg_poll: Arc<atomic::AtomicBool>,
    bg_handles: OnceLock<(std::thread::JoinHandle<()>, std::thread::JoinHandle<()>)>,

    // Work management
    // Keep track of issued IOp and associated variables
    workq: Arc<Mutex<mpsc::Receiver<Arc<cmd::HpuCmd>>>>,
    // Enforce that at most u8::MAX IOp are inflight in the cluster.
    // => All node keep in the same IOp Round
    iop_inflight: Arc<atomic::AtomicU8>,
}

impl HpuCluster {
    pub fn new<F>(config: &HpuConfig, force_reload: bool, gen_lut: &F) -> Result<Self, HpuInstError>
    where
        F: Fn(&HpuParameters, &[u64]) -> HpuGlweLookuptableOwned<u64> + Sync,
    {
        let workload = Arc::new(core::array::from_fn(|_| atomic::AtomicUsize::new(0)));
        let iop_id = Arc::new(atomic::AtomicU8::new(1)); // Value 0 -> mean variables generated by SW

        // Check HpuNode state
        // Hw is reloaded by batch if needed to reduce risk of failure
        HpuHw::lazy_load(&config.fpga.node_id, &config.fpga.ffi, force_reload);

        // Open HpuNode and init them
        // NB: only first node populate signature table
        let mut fw_sig_v = config
            .fpga
            .node_id
            .iter()
            .enumerate()
            .map(|(i, _id)| if i == 0 { Some(HashMap::new()) } else { None })
            .collect::<Vec<_>>();

        let nodes = config
            .fpga
            .node_id
            .par_iter()
            .zip(fw_sig_v.par_iter_mut())
            .map(|(id, sig)| {
                let node = HpuNodeWrapped::new_wrapped(*id, config);

                // init => enforce mutex scope
                {
                    let mut node_lock = node.lock().expect("Error with backend mutex");
                    // Init Fw
                    // Configure Lut addr register
                    node_lock.lut_init();
                    // and IOp translation table
                    node_lock.fw_init(config, sig, gen_lut);

                    // Init HW trace offset
                    node_lock.trace_init();

                    // Init MHDMA
                    node_lock.mhdma_cfg();
                }

                (*id, node)
            })
            .collect::<HashMap<_, _>>();

        // Enforce that all node within the cluster used same HpuParameters
        let params = nodes
            .values()
            .map(|n| &n.params)
            .all_equal_value()
            .map_err(|err| match err.0 {
                Some([pa, pb]) => HpuInstError::InvalidParams(pa.clone(), pb.clone()),
                None => HpuInstError::EmptyDevice,
            })?
            .clone();
        // Extract fw_sig from init vec (only the first node populated it)
        let fw_sig = fw_sig_v
            .into_iter()
            .flatten()
            .next()
            .expect("HpuCluster must contains at least one HpuNode");

        // Construct channel for mt API
        // Keep track of the sender for clone it later on
        let (cmd_tx, cmd_rx) = mpsc::channel();

        // Construct self
        let cluster = Self {
            nodes,
            workload,
            iop_id,
            cmd_tx,
            params,
            fw_sig: Arc::new(fw_sig),
            dyn_fw_sig: Arc::new(Mutex::new(HashMap::new())),
            iop_inflight: Arc::new(atomic::AtomicU8::new(0)),
            bg_poll: Arc::new(atomic::AtomicBool::new(false)),
            bg_handles: OnceLock::new(),
            workq: Arc::new(Mutex::new(cmd_rx)),
        };

        // Start polling thread in the background
        cluster.run_polling(std::time::Duration::from_micros(config.fpga.polling_us));
        Ok(cluster)
    }

    /// Spawn a background thread that handle periodically update HW state
    /// WARN: Variable still required lock on HpuBackend for allocation. Thus ensure to release the
    /// lock periodically NB: This should be replaced by Irq when available
    // TODO: Check if this stmt is still valid
    fn run_polling(&self, tick: std::time::Duration) {
        let Self {
            nodes,
            workload,
            bg_handles,
            bg_poll,
            iop_inflight,
            workq,
            ..
        } = self;

        if bg_poll.load(atomic::Ordering::SeqCst) {
            // background threads already running
            // -> nothing to do
            return;
        };

        bg_poll.store(true, atomic::Ordering::SeqCst);
        let bg_workq = (
            bg_poll.clone(),
            nodes.clone(),
            iop_inflight.clone(),
            workq.clone(),
        );
        let bg_ackq = (
            bg_poll.clone(),
            nodes.clone(),
            iop_inflight.clone(),
            workload.clone(),
        );
        let _ = bg_handles.get_or_init(|| {
            (
                std::thread::spawn(move || {
                    let (poll, nodes, iop_inflight, workq) = bg_workq;
                    while poll.load(atomic::Ordering::SeqCst) {
                        std::thread::sleep(tick);
                        let workq_lock = workq.lock().expect("Encounter error with workq Mutex");
                        while let Ok(cmd) = workq_lock.try_recv() {
                            // Check max inflight IOp
                            while u8::MAX == iop_inflight.load(atomic::Ordering::SeqCst) {
                                std::thread::sleep(tick);
                            }
                            for node in nodes.iter() {
                                let mut node_lock = node.1.lock().expect("Issue with node Mutex");
                                node_lock.workq_push(cmd.clone());
                            }
                            iop_inflight.fetch_add(1, atomic::Ordering::SeqCst);
                        }
                    }
                }),
                std::thread::spawn(move || {
                    let (poll, nodes, iop_inflight, workload) = bg_ackq;
                    while poll.load(atomic::Ordering::SeqCst) {
                        std::thread::sleep(tick);
                        for (id, node) in nodes.iter() {
                            let mut lock = node.lock().unwrap();
                            let (ack_cnt, done_cnt) = lock.flush_ackq();
                            // Variable state are handled in node
                            // Only update associated workload/inflight counter here
                            workload[*id as usize].fetch_sub(ack_cnt, atomic::Ordering::SeqCst);
                            iop_inflight.fetch_sub(done_cnt as u8, atomic::Ordering::SeqCst);
                        }
                    }
                }),
            )
        });
    }
}

impl Drop for HpuCluster {
    fn drop(&mut self) {
        // Required background polling thread to stop
        // This enable proper release of the associated HpuBackend
        self.bg_poll.store(false, atomic::Ordering::SeqCst);

        if let Some((workq_handle, ackq_handle)) = self.bg_handles.take() {
            workq_handle
                .join()
                .expect("Work_queue Background thread failed to stop properly");
            ackq_handle
                .join()
                .expect("Ack_queue Background thread failed to stop properly");
        }
    }
}

impl HpuCluster {
    pub fn params(&self) -> &HpuParameters {
        &self.params
    }

    /// Signature of every predefined `StaticIOp`, per configured integer width.
    pub(crate) fn fw_sig(&self) -> &HashMap<(StaticIOp, u16), IOpSig> {
        &self.fw_sig
    }

    /// Signature of every dynamically-registered (zhc graph) IOp, keyed by its runtime-allocated
    /// opcode. Grown over time by [`Self::fw_dyn_init`].
    pub(crate) fn dyn_fw_sig(&self) -> &Mutex<HashMap<IOpcode, IOpSig>> {
        &self.dyn_fw_sig
    }

    /// Look up the `Signature<Type>`/required-node-count of a given IOp: `fw_sig` for
    /// predefined `StaticIOp` (keyed by the concrete integer width it's being applied at),
    /// `dyn_fw_sig` for dynamically-registered (zhc graph) ones.
    pub(crate) fn get_signature(&self, fw_mode: FwMode, opcode: IOpcode, integer_w: u16) -> IOpSig {
        match fw_mode {
            FwMode::Static => self
                .fw_sig()
                .get(&(StaticIOp::from_opcode(opcode.0), integer_w))
                .unwrap_or_else(|| {
                    panic!("No signature registered for {opcode:?} at integer width {integer_w}")
                })
                .clone(),
            FwMode::Dynamic => self
                .dyn_fw_sig()
                .lock()
                .expect("Error with dyn_fw_sig mutex")
                .get(&opcode)
                .unwrap_or_else(|| panic!("No signature registered for dynamic {opcode:?}"))
                .clone(),
        }
    }
}

impl HpuCluster {
    /// Register a new dynamic fw entry in each node and kept track of its signature at cluster
    /// level (c.f. [`Self::dyn_fw_sig`]).
    pub(crate) fn fw_dyn_init<F>(
        &self,
        pipeline: Pipeline,
        gen_lut: &F,
    ) -> Result<Arc<DynFwEntry>, DynFwError>
    where
        F: Fn(&HpuParameters, &[u64]) -> HpuGlweLookuptableOwned<u64> + Sync,
    {
        // Common pipeline stages
        let mut pipeline = pipeline;
        let fingerprint = pipeline.get_fingerprint();
        let proto = pipeline.get_prototype().clone();
        let lut_registry = pipeline.get_lut_registry().clone();
        let used_nodes = pipeline.get_multi_hpu_config().n_hpus;
        let sig: IOpSig = (proto, used_nodes);
        let doplang = pipeline.get_multi_doplang();

        // Parallel over nodes
        // Each of them has its own relocation table, no recompute of the above.
        let entries = self
            .par_iter()
            .map(|(_id, node)| {
                let mut node_lock = node.lock().expect("Error with backend mutex");
                node_lock.fw_dyn_init(fingerprint, sig.clone(), doplang, &lut_registry, gen_lut)
            })
            .collect::<Result<Vec<_>, _>>()?;

        let all_match = entries.windows(2).all(|w| w[0].iop() == w[1].iop());
        if !all_match {
            Err(DynFwError::UnsyncView)
        } else {
            // Kept track of the associated signature at cluster level
            self.dyn_fw_sig
                .lock()
                .expect("Error with dyn_fw_sig mutex")
                .insert(entries[0].iop(), sig);

            Ok(entries[0].clone())
        }
    }
}

impl HpuCluster {
    /// Compute ordered list of usable nodes
    /// Nodes are sorted by workload and rhs position
    pub(crate) fn usable_nodes(&self, hpu_id: &[u8], rhs_ct: &[HpuVarWrapped]) -> Vec<u8> {
        // Extract inputs position
        let inputs_pos_weight = rhs_ct.iter().map(|v| v.hpu_id.0 as usize).fold(
            [0usize; MAX_HPU_IN_CLUSTER],
            |mut acc, hid| {
                acc[hid] += 1;
                acc
            },
        );
        // Compute node weight
        let mut hpu_weight = std::iter::zip(inputs_pos_weight.iter(), self.workload.iter())
            .enumerate()
            .map(|(i, (p, w))| {
                // To prevent issue with ordering of unload node (i.e. properly take var_pos when
                // all load is at 0) A default workload of operands size is added,
                // this prevent to have underflow on weight computation
                let dflt_weight = rhs_ct.len() * VAR_POS_WEIGHT;
                let work_weight = w.load(atomic::Ordering::SeqCst);
                let pos_weight = *p * VAR_POS_WEIGHT;
                (i as u8, dflt_weight + work_weight - pos_weight)
            })
            .collect::<Vec<_>>();
        hpu_weight.sort_by_key(|x| x.1);

        // Kept only the available ones
        hpu_weight
            .into_iter()
            .filter(|w| hpu_id.contains(&w.0))
            .map(|(i, _w)| i)
            .collect::<Vec<_>>()
    }

    /// Compute Hpu mapping based on various heuristics
    /// Currently take into account:
    /// * Cluster nodes workload
    /// * Operand position
    ///
    /// NB: It's mandatory that node owning the destination data is part of the compute
    pub(crate) fn compute_cmd_map(
        &self,
        hpu_id: &[u8],
        used_nodes: u8,
        dst: &[HpuVarWrapped],
        rhs_ct: &[HpuVarWrapped],
    ) -> IOpMapping {
        // Split it in two categories and ordered them back
        //  a) Node that must belong to the IOp (because they own a destination)
        //  b) Backup Node that optionally could by part of the Iop
        let dst_pos = dst.iter().map(|v| v.hpu_id.0).collect::<HashSet<_>>();
        let (mut hpu_ord, hpu_opt): (Vec<_>, Vec<_>) = self
            .usable_nodes(hpu_id, rhs_ct)
            .into_iter()
            .partition(|x| dst_pos.contains(x));

        // Check that Hpu invariantes are satisfied
        assert!(
            used_nodes as usize >= hpu_ord.len(),
            "Error: dst variables are spread on more nodes than compute"
        );
        // Check that dst var arn't on filtered out node
        assert_eq!(
            hpu_ord.len(),
            dst_pos.len(),
            "Error with dst variables position. Some dst variable are on unused nodes"
        );
        // Append optional nodes
        hpu_ord.extend_from_slice(&hpu_opt);
        IOpMapping::from((hpu_ord, used_nodes))
    }

    /// Workload getter
    pub(crate) fn workload(&self) -> &[atomic::AtomicUsize; MAX_HPU_IN_CLUSTER] {
        &self.workload
    }

    /// Return current IOp id and increment internal counter
    /// IOp id is used to enforce data validity across a chain of inter-dependant IOp
    pub(crate) fn gen_iop_id(&self) -> IOpId {
        let mut raw_id = self.iop_id.fetch_add(1, atomic::Ordering::SeqCst);
        while raw_id == 0 {
            raw_id = self.iop_id.fetch_add(1, atomic::Ordering::SeqCst);
        }
        IOpId(raw_id)
    }
}

impl std::ops::Deref for HpuCluster {
    type Target = HashMap<u8, HpuNodeWrapped>;

    fn deref(&self) -> &Self::Target {
        &self.nodes
    }
}

/// Wrapped HpuCluster inside an Arc to easily shared a read-only reference
#[derive(Clone)]
pub struct HpuClusterWrapped(Arc<HpuCluster>);

impl HpuClusterWrapped {
    pub fn new_wrapped<F>(
        config: &HpuConfig,
        force_reload: bool,
        gen_lut: &F,
    ) -> Result<Self, HpuInstError>
    where
        F: Fn(&HpuParameters, &[u64]) -> HpuGlweLookuptableOwned<u64> + Sync,
    {
        let cluster = HpuCluster::new(config, force_reload, gen_lut)?;
        Ok(Self(Arc::new(cluster)))
    }
}

impl std::ops::Deref for HpuClusterWrapped {
    type Target = Arc<HpuCluster>;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl HpuClusterWrapped {
    /// Construct an Hpu variable from a vector of HpuLweCiphertext
    /// Allocation is made on the less loaded node
    ///
    /// _NB_: Workload management is done at variable allocation. It's not perfect but easier in
    /// first time.
    pub fn new_var_from(
        &self,
        ct: Vec<HpuLweCiphertextOwned<u64>>,
        spec: zhc::builder::CiphertextSpec,
        pos: Option<crate::asm::PhysId>,
    ) -> HpuVarWrapped {
        // Compute workload and allocate on the less loaded node
        let trgt_id = if let Some(hid) = pos {
            hid
        } else {
            let hid = self
                .nodes
                .keys()
                .map(|id| {
                    (
                        *id,
                        self.workload[*id as usize].load(atomic::Ordering::SeqCst),
                    )
                })
                .sorted_by(|a, b| Ord::cmp(&a.1, &b.1))
                .map(|x| x.0)
                .next()
                .expect("HpuCluster must contains at least one HpuNode");
            PhysId(hid)
        };

        tracing::debug!("HpuVariable will be created on Hpu {trgt_id}");

        HpuVarWrapped::new_from(trgt_id, self.clone(), self.params.clone(), ct, spec)
    }
}

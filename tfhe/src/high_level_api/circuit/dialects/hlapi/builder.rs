    // -- Shifts / Rotates --
    // FHE/FHE form requires the rhs to be FheUint(rhs_bits).
    // FHE/scalar form encodes the shift amount in the op's payload.
    // scalar/FHE and scalar/scalar are not supported.

    fn shift_rhs_bits(&self, r: ValueId, op: &'static str) -> Result<u32, BuilderError> {
        match self.kind_of(r) {
            ValueKind::FheUint(bits) => Ok(bits as u32),
            other => Err(BuilderErrorKind::IncompatibleKind {
                value: r,
                kind: other,
            }
            .at(op)),
        }
    }


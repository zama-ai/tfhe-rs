    /// Variadic sum. All inputs must have the same kind. Returns
    /// [`BuilderErrorKind::EmptyInput`] if `values` is empty.
    pub fn fhe_sum(&mut self, values: &[ValueId]) -> Result<ValueId, BuilderError> {
        const OP: &str = "fhe_sum";
        let first = *values.first().ok_or(BuilderErrorKind::EmptyInput.at(OP))?;
        let kind = self.narrow_to_fhe_int_kind(first, OP)?;
        let n = values.len() as u32;
        let args: zhc_utils::small::SmallVec<ValId> = values.iter().map(|v| v.raw).collect();
        let val_ids = self.try_add_op(OP, HlInstructionSet::FheSum { kind, n }, args)?;
        debug_assert_eq!(val_ids.len(), 1);
        Ok(val_ids[0])
    }


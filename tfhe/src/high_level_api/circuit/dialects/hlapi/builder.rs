    pub fn fhe_select(
        &mut self,
        cond: ValueId,
        then_val: impl Into<Operand>,
        else_val: impl Into<Operand>,
    ) -> Result<ValueId, BuilderError> {
        const OP: &str = "fhe_select";
        let cond_kind = self.kind_of(cond);
        if cond_kind != ValueKind::FheBool {
            return Err(BuilderErrorKind::IncompatibleKind {
                value: cond,
                kind: cond_kind,
            }
            .at(OP));
        }
        match (then_val.into(), else_val.into()) {
            (Operand::Ref(t), Operand::Ref(e)) if self.is_fhe(t) && self.is_fhe(e) => {
                let kind = self.narrow_to_fhe_int_kind(t, OP)?;
                self.add_unary(
                    OP,
                    HlInstructionSet::Select { kind },
                    svec![cond.raw, t.raw, e.raw],
                )
            }
            (Operand::Ref(t), other) if self.is_fhe(t) => {
                let kind = self.narrow_to_fhe_int_kind(t, OP)?;
                let clear_id = self.materialize_clear(OP, other, kind.as_clear_kind())?;
                self.add_unary(
                    OP,
                    HlInstructionSet::SelectFheScalar { kind },
                    svec![cond.raw, t.raw, clear_id.raw],
                )
            }
            (other, Operand::Ref(e)) if self.is_fhe(e) => {
                let kind = self.narrow_to_fhe_int_kind(e, OP)?;
                let clear_id = self.materialize_clear(OP, other, kind.as_clear_kind())?;
                self.add_unary(
                    OP,
                    HlInstructionSet::SelectScalarFhe { kind },
                    svec![cond.raw, clear_id.raw, e.raw],
                )
            }
            // Both-clear requires an explicit output kind — use
            // `fhe_select_const` instead.
            _ => Err(BuilderErrorKind::UnsupportedOperandCombination.at(OP)),
        }
    }

    /// Paired select: `if cond { (b, a) } else { (a, b) }`. Both branches
    /// must be encrypted (no scalar variants — the integer layer has
    /// none). Mirrors `ServerKey::flip_parallelized`.
    pub fn fhe_flip(
        &mut self,
        cond: ValueId,
        a: impl Into<Operand>,
        b: impl Into<Operand>,
    ) -> Result<(ValueId, ValueId), BuilderError> {
        const OP: &str = "fhe_flip";
        match (a.into(), b.into()) {
            (Operand::Ref(a), Operand::Ref(b)) if self.is_fhe(a) && self.is_fhe(b) => {
                let kind = self.narrow_to_fhe_int_kind(a, OP)?;
                self.add_pair_op(
                    OP,
                    HlInstructionSet::FheFlip { kind },
                    svec![cond.raw, a.raw, b.raw],
                )
            }
            _ => Err(BuilderErrorKind::UnsupportedOperandCombination.at(OP)),
        }
    }

    /// `fhe_select` for the case where both branches are clear scalars.
    /// The output `kind` must be supplied explicitly because no encrypted
    /// operand pins it down.
    pub fn fhe_select_const(
        &mut self,
        cond: ValueId,
        true_value: impl Into<ScalarValue>,
        false_value: impl Into<ScalarValue>,
        kind: FheIntKind,
    ) -> Result<ValueId, BuilderError> {
        const OP: &str = "fhe_select_const";
        Self::check_fhe_int_kind_bits(kind, OP)?;
        let cond_kind = self.kind_of(cond);
        if cond_kind != ValueKind::FheBool {
            return Err(BuilderErrorKind::IncompatibleKind {
                value: cond,
                kind: cond_kind,
            }
            .at(OP));
        }
        let clear_kind = kind.as_clear_kind();
        // Validate both values before emitting either constant so an error
        // never leaves an orphan operation in the IR.
        let true_value = Self::normalize_scalar(true_value.into(), clear_kind, OP)?;
        let false_value = Self::normalize_scalar(false_value.into(), clear_kind, OP)?;
        let true_id = self.emit_constant(OP, true_value, clear_kind)?;
        let false_id = self.emit_constant(OP, false_value, clear_kind)?;
        self.add_unary(
            OP,
            HlInstructionSet::SelectScalarScalar { kind },
            svec![cond.raw, true_id.raw, false_id.raw],
        )
    }


    /// Fused `(lhs * rhs) / div_scalar` with widening to 2x bits to prevent
    /// the multiply from overflowing. Mirrors the HL
    /// `FusedMulScalarDiv` semantics: cast both operands to a wider kind,
    /// multiply, divide by `div_scalar` (in the wider kind), then cast back.
    ///
    /// Constraint: `lhs` width must be ≤ 64 bits (so the wide-doubled width
    /// is ≤ 128, which fits in `ScalarValue::Unsigned(u128)` /
    /// `Signed(i128)`).
    pub fn fhe_fused_mul_scalar_div(
        &mut self,
        lhs: ValueId,
        rhs: ValueId,
        div_scalar: impl Into<ScalarValue>,
    ) -> Result<ValueId, BuilderError> {
        const OP: &str = "fhe_fused_mul_scalar_div";
        let kind = self.narrow_to_fhe_int_kind(lhs, OP)?;
        let rhs_kind = self.narrow_to_fhe_int_kind(rhs, OP)?;
        if rhs_kind != kind {
            return Err(BuilderErrorKind::MismatchedOperandKinds {
                lhs: kind.into(),
                rhs: rhs_kind.into(),
            }
            .at(OP));
        }
        let narrow_bits: u32 = match kind {
            FheIntKind::Uint(n) | FheIntKind::Int(n) => n,
        };
        if narrow_bits > 64 {
            return Err(BuilderErrorKind::IncompatibleKind {
                value: lhs,
                kind: kind.into(),
            }
            .at(OP));
        }
        let wide_bits = narrow_bits * 2;
        let (narrow_kind, wide_kind) = match kind {
            FheIntKind::Uint(_) => (FheKind::Uint(narrow_bits), FheKind::Uint(wide_bits)),
            FheIntKind::Int(_) => (FheKind::Int(narrow_bits), FheKind::Int(wide_bits)),
        };
        // Validate the scalar before starting this multi-op expansion. Once
        // emission begins, all remaining signatures are guaranteed by the
        // kinds computed above.
        let div_scalar = Self::normalize_scalar(div_scalar.into(), wide_kind.as_clear_kind(), OP)?;
        if matches!(
            div_scalar,
            ScalarValue::Unsigned(0) | ScalarValue::Signed(0)
        ) {
            return Err(BuilderErrorKind::DivisionByZeroScalar.at(OP));
        }
        let wide_lhs = self.fhe_cast(lhs, wide_kind)?;
        let wide_rhs = self.fhe_cast(rhs, wide_kind)?;
        let wide_product = self.fhe_mul(wide_lhs, wide_rhs)?;
        let wide_result = self.fhe_div(wide_product, Operand::Scalar(div_scalar))?;
        self.fhe_cast(wide_result, narrow_kind)
    }

    /// Fused `(value * mul_scalar) / div_scalar` with widening to 2x bits.
    /// Mirrors HL `FusedScalarMulScalarDiv`. Same width constraint as
    /// `fhe_fused_mul_scalar_div`.
    pub fn fhe_fused_scalar_mul_scalar_div(
        &mut self,
        value: ValueId,
        mul_scalar: impl Into<ScalarValue>,
        div_scalar: impl Into<ScalarValue>,
    ) -> Result<ValueId, BuilderError> {
        const OP: &str = "fhe_fused_scalar_mul_scalar_div";
        let kind = self.narrow_to_fhe_int_kind(value, OP)?;
        let narrow_bits: u32 = match kind {
            FheIntKind::Uint(n) | FheIntKind::Int(n) => n,
        };
        if narrow_bits > 64 {
            return Err(BuilderErrorKind::IncompatibleKind {
                value,
                kind: kind.into(),
            }
            .at(OP));
        }
        let wide_bits = narrow_bits * 2;
        let (narrow_kind, wide_kind) = match kind {
            FheIntKind::Uint(_) => (FheKind::Uint(narrow_bits), FheKind::Uint(wide_bits)),
            FheIntKind::Int(_) => (FheKind::Int(narrow_bits), FheKind::Int(wide_bits)),
        };
        let clear_kind = wide_kind.as_clear_kind();
        let mul_scalar = Self::normalize_scalar(mul_scalar.into(), clear_kind, OP)?;
        let div_scalar = Self::normalize_scalar(div_scalar.into(), clear_kind, OP)?;
        if matches!(
            div_scalar,
            ScalarValue::Unsigned(0) | ScalarValue::Signed(0)
        ) {
            return Err(BuilderErrorKind::DivisionByZeroScalar.at(OP));
        }
        let wide_value = self.fhe_cast(value, wide_kind)?;
        let wide_product = self.fhe_mul(wide_value, Operand::Scalar(mul_scalar))?;
        let wide_result = self.fhe_div(wide_product, Operand::Scalar(div_scalar))?;
        self.fhe_cast(wide_result, narrow_kind)
    }


    // -- OPRF (oblivious pseudo-random) --

    /// Generate an oblivious pseudo-random ciphertext, full-range uniform.
    /// Works for any output kind (`FheUint`, `FheInt`, `FheBool`).
    /// `seed` must be a `ValueKind::Seed` value (typically a circuit input
    /// created via `input(ValueKind::Seed)`). Keeping the seed a runtime value
    /// means a fresh seed is supplied per execution without rebuilding the
    /// circuit.
    pub fn oprf(&mut self, value_kind: ValueKind, seed: ValueId) -> Result<ValueId, BuilderError> {
        const OP: &str = "oprf";
        Self::check_oprf_kind(value_kind, &OprfMode::Full, OP)?;
        Self::check_value_kind_bits(value_kind, OP)?;
        self.emit_oprf(OP, value_kind, seed, OprfMode::Full)
    }

    /// Generate an oblivious pseudo-random ciphertext in `[0, 2^bits)`.
    /// Rejects `FheBool`. See [`Self::oprf`] for the `seed` argument.
    pub fn oprf_bounded(
        &mut self,
        value_kind: ValueKind,
        seed: ValueId,
        bits: u64,
    ) -> Result<ValueId, BuilderError> {
        const OP: &str = "oprf_bounded";
        let mode = OprfMode::Bounded { bits };
        Self::check_oprf_kind(value_kind, &mode, OP)?;
        Self::check_value_kind_bits(value_kind, OP)?;
        // `check_oprf_kind` already restricted Bounded to `FheUint`/`FheInt`,
        // so a width is always available here.
        let width = match value_kind {
            ValueKind::FheUint(n) | ValueKind::FheInt(n) => n as u32,
            _ => unreachable!("check_oprf_kind rejects non-integer kinds for Bounded"),
        };
        if bits == 0 || bits > u64::from(width) {
            return Err(BuilderErrorKind::InvalidOprfBoundedBits { bits, width }.at(OP));
        }
        self.emit_oprf(OP, value_kind, seed, mode)
    }

    /// Generate an oblivious pseudo-random ciphertext almost-uniform on
    /// `[0, upper)`. **`FheUint` only.**
    /// `max_distance` controls bias budget; `None` matches HL's `2^-128`.
    /// See [`Self::oprf`] for the `seed` argument.
    pub fn oprf_custom_range(
        &mut self,
        value_kind: ValueKind,
        seed: ValueId,
        upper: NonZeroU64,
        max_distance: Option<f64>,
    ) -> Result<ValueId, BuilderError> {
        const OP: &str = "oprf_custom_range";
        Self::check_value_kind_bits(value_kind, OP)?;
        let ValueKind::FheUint(width) = value_kind else {
            return Err(BuilderErrorKind::InvalidOprfMode {
                value_kind,
                mode_name: OprfMode::CustomRange {
                    upper,
                    max_distance: None,
                }
                .name(),
            }
            .at(OP));
        };
        let width = width as u32;
        let max_value = upper.get() - 1;
        let required_bits = u64::BITS - max_value.leading_zeros();
        if required_bits > width {
            return Err(BuilderErrorKind::InvalidOprfUpperBound {
                upper: upper.get(),
                width,
            }
            .at(OP));
        }

        let max_distance = max_distance
            .map(|d| {
                // Mirrors the classic HLAPI requirement `0 < max_distance < 1`.
                // The comparisons also reject NaN, so the `NonNanF64`
                // construction below cannot fail afterwards.
                if d > 0.0 && d < 1.0 {
                    NonNanF64::new(d).map_err(|_| BuilderErrorKind::InvalidOprfMaxDistance.at(OP))
                } else {
                    Err(BuilderErrorKind::InvalidOprfMaxDistance.at(OP))
                }
            })
            .transpose()?;

        // The custom-range primitive deliberately rejects powers of two;
        // those ranges are exactly uniform and use the bounded primitive.
        // `upper == 1` maps to zero random bits, which produces the sole
        // possible value (zero).
        if upper.is_power_of_two() {
            return self.emit_oprf(
                OP,
                value_kind,
                seed,
                OprfMode::Bounded {
                    bits: u64::from(upper.ilog2()),
                },
            );
        }

        let mode = OprfMode::CustomRange {
            upper,
            max_distance,
        };
        self.emit_oprf(OP, value_kind, seed, mode)
    }

    fn emit_oprf(
        &mut self,
        op: &'static str,
        value_kind: ValueKind,
        seed: ValueId,
        mode: OprfMode,
    ) -> Result<ValueId, BuilderError> {
        let seed_kind = self.kind_of(seed);
        if seed_kind != ValueKind::Seed {
            return Err(BuilderErrorKind::IncompatibleKind {
                value: seed,
                kind: seed_kind,
            }
            .at(op));
        }
        self.add_unary(
            op,
            HlInstructionSet::FheOprf { value_kind, mode },
            svec![seed.raw],
        )
    }

    /// Encrypted membership test: returns an `FheBool` that's `true` iff
    /// `needle` equals at least one element of `haystack`.
    ///
    /// `needle` can be either an FHE value (matching the haystack's kind)
    /// or a clear scalar.
    ///
    /// Returns [`BuilderErrorKind::EmptyInput`] if `haystack` is empty.
    pub fn fhe_contains(
        &mut self,
        haystack: &[ValueId],
        needle: impl Into<Operand>,
    ) -> Result<ValueId, BuilderError> {
        const OP: &str = "fhe_contains";
        let first = *haystack
            .first()
            .ok_or(BuilderErrorKind::EmptyInput.at(OP))?;
        let kind = self.narrow_to_fhe_int_kind(first, OP)?;
        for &value in &haystack[1..] {
            let value_kind = self.narrow_to_fhe_int_kind(value, OP)?;
            if value_kind != kind {
                return Err(BuilderErrorKind::MismatchedOperandKinds {
                    lhs: kind.into(),
                    rhs: value_kind.into(),
                }
                .at(OP));
            }
        }
        let n = haystack.len() as u32;
        match needle.into() {
            Operand::Ref(needle) if self.is_fhe(needle) => {
                let needle_kind = self.narrow_to_fhe_int_kind(needle, OP)?;
                if needle_kind != kind {
                    return Err(BuilderErrorKind::MismatchedOperandKinds {
                        lhs: kind.into(),
                        rhs: needle_kind.into(),
                    }
                    .at(OP));
                }
                let mut inputs: SmallVec<ValId> = svec![needle.raw];
                inputs.extend(haystack.iter().map(|h| h.raw));
                self.add_unary(OP, HlInstructionSet::FheContains { kind, n }, inputs)
            }
            other => {
                let clear_id = self.materialize_clear(OP, other, kind.as_clear_kind())?;
                // Clear needle is first (mirrors `FheContains` having needle-first),
                // haystack follows.
                let mut inputs: SmallVec<ValId> = svec![clear_id.raw];
                inputs.extend(haystack.iter().map(|h| h.raw));
                self.add_unary(OP, HlInstructionSet::FheContainsScalar { kind, n }, inputs)
            }
        }
    }

    fn check_oprf_kind(
        value_kind: ValueKind,
        mode: &OprfMode,
        op: &'static str,
    ) -> Result<(), BuilderError> {
        let ok = matches!(
            (value_kind, mode),
            (ValueKind::FheUint(_), _)
                | (
                    ValueKind::FheInt(_),
                    OprfMode::Full | OprfMode::Bounded { .. }
                )
                | (ValueKind::FheBool, OprfMode::Full)
        );
        if ok {
            Ok(())
        } else {
            Err(BuilderErrorKind::InvalidOprfMode {
                value_kind,
                mode_name: mode.name(),
            }
            .at(op))
        }
    }

    /// True if `value`'s kind is one of the FHE-encrypted kinds
    /// (`FheUint`, `FheInt`, `FheBool`).
    fn is_fhe(&self, value: ValueId) -> bool {
        matches!(
            self.kind_of(value),
            ValueKind::FheUint(_) | ValueKind::FheInt(_) | ValueKind::FheBool
        )
    }

    pub fn kind_of(&self, value: ValueId) -> ValueKind {
        self.ir.get_val(value.raw).get_type()
    }

    /// Materialize the clear-side of a polymorphic binary op to a circuit
    /// `ValueId`: returns the existing `Ref` id (kind validation happens
    /// at IR signature check), or emits a `Constant` for a `Scalar(_)`
    /// literal. Callers guard with [`ValueId::is_fhe`] / a `Ref(...) if
    /// self.is_fhe(fhe)` match arm so that the *other* `Operand` here is
    /// always a clear-side input.
    fn materialize_clear(
        &mut self,
        op: &'static str,
        clear: Operand,
        kind: ClearKind,
    ) -> Result<ValueId, BuilderError> {
        match clear {
            Operand::Ref(id) => Ok(id),
            Operand::Scalar(s) => self.emit_constant(op, s, kind),
        }
    }

    /// Finishes the builder and returns the circuit
    pub fn build(self) -> Circuit {
        #[cfg(debug_assertions)]
        self.debug_assert_kvstore_invariant();
        Circuit {
            ir: self.ir,
            inputs: self.inputs,
            outputs: self.outputs,
        }
    }

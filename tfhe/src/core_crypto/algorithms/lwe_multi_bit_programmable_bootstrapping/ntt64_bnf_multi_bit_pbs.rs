//! Module containing primitives pertaining to the [`LWE multi-bit programmable
//! bootstrap`](`crate::core_crypto::entities::LweMultiBitBootstrapKey`) using a 64 bits NTT for the
//! polynomial multiplications with a "back and forth" (bnf) approach: ciphertexts live on a power
//! of two modulus and are switched to the NTT prime modulus (and back) around each external
//! product.
//!
//! Contrary to the FFT based multi-bit PBS, the bootstrap key is not converted to the transformed
//! domain ahead of time. It is kept in the standard domain, modulus switched to the NTT modulus
//! (see
//! [`modulus_switch_lwe_multi_bit_bootstrap_key_to_ntt64_modulus`](`crate::core_crypto::algorithms::modulus_switch_lwe_multi_bit_bootstrap_key_to_ntt64_modulus`)),
//! and the multi-bit key bundle of each group of LWE mask elements is computed in the standard
//! domain before being sent to the NTT domain.
//!
//! The key bundle is also built differently from the other multi-bit implementations: the GGSW
//! encrypting the product of the negated key bits of the group (the "0..0" bit pattern) is not
//! used and each of the other GGSW ciphertexts is multiplied by $X^{c} - 1$ instead of $X^{c}$,
//! $c$ being the associated combination of modulus switched mask elements. The bundle therefore
//! encrypts $X^{\langle a, s \rangle} - 1$ (rather than $X^{\langle a, s \rangle}$) and the
//! accumulator is updated in a CMUX like fashion: $acc \leftarrow acc + bundle \boxdot acc$.

use super::{MultiBitModulusSwitchedLweCiphertext, StandardMultiBitModulusSwitchedCt};

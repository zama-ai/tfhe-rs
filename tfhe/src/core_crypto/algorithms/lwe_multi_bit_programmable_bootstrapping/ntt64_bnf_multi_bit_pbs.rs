/// Compute the multi-bit key bundle of a group of LWE mask elements in the standard domain, modulo
/// the (non power of two) [`CiphertextModulus`] of the GGSW ciphertexts, for the 64 bits NTT "back
/// and forth" multi-bit PBS.
///
/// The GGSW ciphertexts of the group are expected to be ordered as generated by
/// [`generate_lwe_multi_bit_bootstrap_key`](`crate::core_crypto::algorithms::generate_lwe_multi_bit_bootstrap_key`):
/// the first one encrypts the product of the negated key bits of the group and is not used here,
/// each of the remaining ones is multiplied by $X^{c} - 1$, $c$ being the corresponding modulus
/// switched combination of mask elements given by `switched_degrees`, and the results are summed.
///
/// The resulting `multi_bit_ggsw` encrypts $X^{\langle a, s \rangle} - 1$ and has to be used in a
/// CMUX like fashion: $acc \leftarrow acc + multi\\_bit\\_ggsw \boxdot acc$.
///
/// `tmp_ggsw_buffer` is a scratch buffer with the same dimensions as `multi_bit_ggsw`.
///
/// # Panics
///
/// This function will panic if the ciphertext modulus of `multi_bit_ggsw` is a power of two or if
/// the number of GGSW ciphertexts in the group does not match the number of degrees in
/// `switched_degrees` plus one.
pub fn std_prepare_multi_bit_ggsw_ntt64_bnf<GgswBufferCont, TmpPolyBufferCont, GgswGroupCont>(
    multi_bit_ggsw: &mut GgswCiphertext<GgswBufferCont>,
    tmp_poly_buffer: &mut Polynomial<TmpPolyBufferCont>,
    ggsw_group: &GgswCiphertextList<GgswGroupCont>,
    switched_degrees: impl Iterator<Item = usize>,
) where
    GgswBufferCont: ContainerMut<Element = u64>,
    TmpPolyBufferCont: ContainerMut<Element = u64>,
    GgswGroupCont: Container<Element = u64>,
{
    let ciphertext_modulus = multi_bit_ggsw.ciphertext_modulus();
    assert!(
        !ciphertext_modulus.is_compatible_with_native_modulus(),
        "std_prepare_multi_bit_ggsw_ntt64_bnf requires a non power of two CiphertextModulus, \
        got {ciphertext_modulus:?}"
    );
    let modulus: u64 = ciphertext_modulus.get_custom_modulus().cast_into();

    let mut multi_bit_ggsw = multi_bit_ggsw.as_mut_view();

    let mut ggsw_group_iter = ggsw_group.iter();

    // Keygen guarantees the first GGSW corresponds to the case where both key bits are 0.
    // In the formulation we use, where this corresponds to X^0 == 1, this GGSW is not needed in the
    // creation of the key bundle.
    let _ggsw_a_none = ggsw_group_iter.next().unwrap();

    let mut iter = ggsw_group_iter.zip_eq(switched_degrees);

    // First ggsw mul result is assigned to the buffer
    {
        let (first_ggsw, first_switched_degree) = iter.next().unwrap();

        for (mut dst_polynomial, src_polynomial) in multi_bit_ggsw
            .as_mut_polynomial_list()
            .iter_mut()
            .zip_eq(first_ggsw.as_polynomial_list().iter())
        {
            // dst = input * X^{switched_degree} - input
            polynomial_wrapping_monic_monomial_mul_and_subtract_custom_mod(
                &mut dst_polynomial,
                &src_polynomial,
                MonomialDegree(first_switched_degree),
                modulus,
            );
        }
    }

    // Further ggsw multiplications are added to the result
    for (std_ggsw, switched_degree) in iter {
        debug_assert_eq!(std_ggsw.ciphertext_modulus(), ciphertext_modulus);

        for (mut dst_poylnomial, src_polynomial) in multi_bit_ggsw
            .as_mut_polynomial_list()
            .iter_mut()
            .zip_eq(std_ggsw.as_polynomial_list().iter())
        {
            // dst = input * X^{switched_degree} - input
            polynomial_wrapping_monic_monomial_mul_and_subtract_custom_mod(
                tmp_poly_buffer,
                &src_polynomial,
                MonomialDegree(switched_degree),
                modulus,
            );

            // Accumulate in the output buffer to build the bundle
            slice_wrapping_add_assign_custom_mod(
                dst_poylnomial.as_mut(),
                tmp_poly_buffer.as_ref(),
                modulus,
            );
        }
    }
}

/// Perform a blind rotation given a [`modulus switched multi-bit LWE
/// ciphertext`](`MultiBitModulusSwitchedLweCiphertext`), modifying a look-up table passed as a
/// [`GLWE ciphertext`](`GlweCiphertext`) and an [`LWE multi-bit bootstrap
/// key`](`LweMultiBitBootstrapKey`) modulus switched to the NTT modulus (see
/// [`modulus_switch_lwe_multi_bit_bootstrap_key_to_ntt64_modulus`](`crate::core_crypto::algorithms::modulus_switch_lwe_multi_bit_bootstrap_key_to_ntt64_modulus`)),
/// using a 64 bits NTT "back and forth" approach. See the [module level
/// documentation](`crate::core_crypto::algorithms::lwe_multi_bit_programmable_bootstrapping::ntt64_bnf_multi_bit_pbs`)
/// for details.
///
/// `thread_count` producer threads compute the multi-bit key bundles while the calling thread
/// performs the external products. With `deterministic_execution` set to `true` the key bundles are
/// consumed in a fixed order, guaranteeing a deterministic output, otherwise they are consumed as
/// soon as they are available.
///
/// See [`multi_bit_programmable_bootstrap_ntt64_bnf_lwe_ciphertext`] for usage.
pub fn multi_bit_ntt64_bnf_blind_rotate_assign<OutputCont, KeyCont>(
    multi_bit_modulus_switched_input: &impl MultiBitModulusSwitchedLweCiphertext,
    accumulator: &mut GlweCiphertext<OutputCont>,
    multi_bit_bsk: &LweMultiBitBootstrapKey<KeyCont>,
    thread_count: ThreadCount,
    deterministic_execution: bool,
) where
    OutputCont: ContainerMut<Element = u64>,
    KeyCont: Container<Element = u64> + Sync,
{
    // For simplicity and given performance is currently not great we only have the deterministic
    // variant written
    let _ = deterministic_execution;
    multi_bit_ntt64_bnf_deterministic_blind_rotate_assign(
        multi_bit_modulus_switched_input,
        accumulator,
        multi_bit_bsk,
        thread_count,
    )
}

/// Deterministic variant of [`multi_bit_ntt64_bnf_blind_rotate_assign`]. Performance may be
/// slightly worse than the non deterministic version.
pub fn multi_bit_ntt64_bnf_deterministic_blind_rotate_assign<OutputCont, KeyCont>(
    switched_modulus_input: &impl MultiBitModulusSwitchedLweCiphertext,
    accumulator: &mut GlweCiphertext<OutputCont>,
    multi_bit_bsk: &LweMultiBitBootstrapKey<KeyCont>,
    thread_count: ThreadCount,
) where
    OutputCont: ContainerMut<Element = u64>,
    KeyCont: Container<Element = u64> + Sync,
{
    assert_eq!(
        switched_modulus_input.lwe_dimension(),
        multi_bit_bsk.input_lwe_dimension(),
        "Mismatched input LweDimension. LweCiphertext input LweDimension {:?}. \
        LweMultiBitBootstrapKey input LweDimension {:?}.",
        switched_modulus_input.lwe_dimension(),
        multi_bit_bsk.input_lwe_dimension(),
    );

    assert_eq!(
        switched_modulus_input.grouping_factor(),
        multi_bit_bsk.grouping_factor(),
        "Mismatched input grouping_factor. LweCiphertext input grouping_factor {:?}. \
        LweMultiBitBootstrapKey grouping_factor {:?}.",
        switched_modulus_input.grouping_factor(),
        multi_bit_bsk.grouping_factor(),
    );

    assert_eq!(
        accumulator.glwe_size(),
        multi_bit_bsk.glwe_size(),
        "Mismatched GlweSize. Accumulator GlweSize {:?}. \
        LweMultiBitBootstrapKey GlweSize {:?}.",
        accumulator.glwe_size(),
        multi_bit_bsk.glwe_size(),
    );

    assert_eq!(
        accumulator.polynomial_size(),
        multi_bit_bsk.polynomial_size(),
        "Mismatched PolynomialSize. Accumulator PolynomialSize {:?}. \
        LweMultiBitBootstrapKey PolynomialSize {:?}.",
        accumulator.polynomial_size(),
        multi_bit_bsk.polynomial_size(),
    );

    assert!(
        thread_count.0 != 0,
        "Got thread_count == 0, this is not supported"
    );

    assert!(
        accumulator
            .ciphertext_modulus()
            .is_compatible_with_native_modulus(),
        "NTT64 back and forth multi bit PBS requires the accumulator to have a power of two \
        CiphertextModulus, got {:?}",
        accumulator.ciphertext_modulus(),
    );

    assert!(
        !multi_bit_bsk
            .ciphertext_modulus()
            .is_compatible_with_native_modulus(),
        "NTT64 back and forth multi bit PBS requires the LweMultiBitBootstrapKey to have been \
        modulus switched to the NTT modulus \
        (see modulus_switch_lwe_multi_bit_bootstrap_key_to_ntt64_modulus), \
        got a power of two CiphertextModulus {:?}",
        multi_bit_bsk.ciphertext_modulus(),
    );

    let glwe_size = multi_bit_bsk.glwe_size();
    let polynomial_size = multi_bit_bsk.polynomial_size();
    let decomposition_base_log = multi_bit_bsk.decomposition_base_log();
    let decomposition_level_count = multi_bit_bsk.decomposition_level_count();
    let bsk_ciphertext_modulus = multi_bit_bsk.ciphertext_modulus();

    // Also checks that the key modulus is usable with a 64 bits NTT of the given size
    let ntt = Ntt64::new(bsk_ciphertext_modulus, polynomial_size);
    let ntt = ntt.as_view();

    let grouping_factor = multi_bit_bsk.grouping_factor();
    let ggsw_per_multi_bit_element = grouping_factor.ggsw_per_multi_bit_element();

    let max_work_index = multi_bit_bsk.multi_bit_input_lwe_dimension().0;

    // One key bundle buffer per producer thread, along with the flag (protected by a mutex and
    // paired with a condvar) indicating whether the buffer holds a bundle ready to be consumed
    let ntt_multi_bit_ggsw_buffers: Vec<_> = (0..thread_count.0)
        .map(|_| {
            (
                Mutex::new(false),
                Condvar::new(),
                Mutex::new(NttGgswCiphertextOwned::<u64>::new(
                    glwe_size,
                    polynomial_size,
                    decomposition_base_log,
                    decomposition_level_count,
                )),
            )
        })
        .collect();

    thread::scope(|s| {
        let produce_multi_bit_ntt_ggsw = |thread_id: usize| {
            let mut std_ggsw_buffer = GgswCiphertext::new(
                0u64,
                glwe_size,
                polynomial_size,
                decomposition_base_log,
                decomposition_level_count,
                bsk_ciphertext_modulus,
            );

            let mut tmp_poly_buffer = Polynomial::new(0u64, polynomial_size);

            let (ready_for_consumer_lock, condvar, ntt_ggsw_buffer) =
                &ntt_multi_bit_ggsw_buffers[thread_id];

            let work_indices = (0..max_work_index).skip(thread_id).step_by(thread_count.0);

            for work_index in work_indices {
                let switched_degrees =
                    switched_modulus_input.switched_modulus_input_mask_per_group(work_index);

                let ggsw_group = multi_bit_bsk.get_sub(
                    work_index * ggsw_per_multi_bit_element.0
                        ..(work_index + 1) * ggsw_per_multi_bit_element.0,
                );

                let mut ready_for_consumer = ready_for_consumer_lock.lock().unwrap();

                // Wait while the buffer is not ready for processing and wait on the condvar
                // to get notified when we can start processing again
                while *ready_for_consumer {
                    ready_for_consumer = condvar.wait(ready_for_consumer).unwrap();
                }

                let mut ntt_ggsw_buffer = ntt_ggsw_buffer.lock().unwrap();

                std_prepare_multi_bit_ggsw_ntt64_bnf(
                    &mut std_ggsw_buffer,
                    &mut tmp_poly_buffer,
                    &ggsw_group,
                    switched_degrees,
                );

                // The bundle is already on the NTT modulus, only the forward NTT is applied. The
                // normalization is applied on the backward path by the external product.
                convert_standard_ggsw_ciphertext_to_ntt64(
                    &std_ggsw_buffer,
                    &mut ntt_ggsw_buffer,
                    ntt,
                    NttLweBootstrapKeyOption::Raw,
                );

                // Drop the lock before we wake other threads
                drop(ntt_ggsw_buffer);

                *ready_for_consumer = true;

                // Wake threads waiting on the condvar
                condvar.notify_all();
            }
        };

        // false positive as the mapping function has side effects (thread spawning)
        #[allow(clippy::needless_collect)]
        let threads: Vec<_> = (0..thread_count.0)
            .map(|thread_id| s.spawn(move || produce_multi_bit_ntt_ggsw(thread_id)))
            .collect();

        // The consumer updates ct0 (the accumulator) in place, ct1 holds a copy of the accumulator
        // to be used as the external product input
        let ct0 = &mut *accumulator;
        let mut ct1 =
            GlweCiphertext::new(0u64, glwe_size, polynomial_size, ct0.ciphertext_modulus());

        let mut buffers = ComputationBuffers::new();

        buffers.resize(
            ntt64_bnf_add_external_product_assign_scratch(glwe_size, polynomial_size, ntt)
                .unaligned_bytes_required(),
        );

        for (ready_lock, condvar, ntt_multi_bit_ggsw) in ntt_multi_bit_ggsw_buffers
            .iter()
            .cycle()
            .take(max_work_index)
        {
            // The bundle encrypts X^{<a, s>} - 1, the accumulator update is acc <- acc + bundle ⊡
            // acc
            ct1.as_mut().copy_from_slice(ct0.as_ref());

            let mut ready = ready_lock.lock().unwrap();

            while !*ready {
                ready = condvar.wait(ready).unwrap();
            }

            let ntt_multi_bit_ggsw = ntt_multi_bit_ggsw.lock().unwrap();

            add_external_product_ntt64_bnf_assign(
                ct0.as_mut_view(),
                ntt_multi_bit_ggsw.as_view(),
                &ct1,
                ntt,
                buffers.stack(),
            );

            drop(ntt_multi_bit_ggsw);

            *ready = false;
            // Wake a single producer thread sleeping on the condvar (only one will get to work
            // anyways)
            condvar.notify_one();
        }

        for t in threads {
            t.join().unwrap();
        }
    });

    // Done at the end to more easily match stimuli requirements
    // Rotate the accumulator by -b_hat
    accumulator
        .as_mut_polynomial_list()
        .iter_mut()
        .for_each(|mut poly| {
            polynomial_wrapping_monic_monomial_div_assign(
                &mut poly,
                MonomialDegree(switched_modulus_input.switched_modulus_input_lwe_body()),
            );
        });
}

/// Perform a programmable bootstrap given an input [`LWE ciphertext`](`LweCiphertext`), a
/// look-up table passed as a [`GLWE ciphertext`](`GlweCiphertext`) and an [`LWE multi-bit bootstrap
/// key`](`LweMultiBitBootstrapKey`) modulus switched to the NTT modulus (see
/// [`modulus_switch_lwe_multi_bit_bootstrap_key_to_ntt64_modulus`](`crate::core_crypto::algorithms::modulus_switch_lwe_multi_bit_bootstrap_key_to_ntt64_modulus`)),
/// using a 64 bits NTT "back and forth" approach. The result is written in the provided output
/// [`LWE ciphertext`](`LweCiphertext`).
///
/// See the [module level
/// documentation](`crate::core_crypto::algorithms::lwe_multi_bit_programmable_bootstrapping::ntt64_bnf_multi_bit_pbs`)
/// for details on the approach and [`multi_bit_ntt64_bnf_blind_rotate_assign`] for the meaning of
/// `thread_count` and `deterministic_execution`.
///
/// # Example
///
/// ```rust
/// use tfhe::core_crypto::prelude::*;
///
/// // DISCLAIMER: these toy example parameters are not guaranteed to be secure or yield correct
/// // computations
/// // Define the parameters for a 4 bits message able to hold the doubled 2 bits message
/// let small_lwe_dimension = LweDimension(742);
/// let glwe_dimension = GlweDimension(1);
/// let polynomial_size = PolynomialSize(2048);
/// let lwe_noise_distribution =
///     Gaussian::from_dispersion_parameter(StandardDev(0.000007069849454709433), 0.0);
/// let glwe_noise_distribution =
///     Gaussian::from_dispersion_parameter(StandardDev(0.00000000000000029403601535432533), 0.0);
/// let pbs_base_log = DecompositionBaseLog(23);
/// let pbs_level = DecompositionLevelCount(1);
/// let grouping_factor = LweBskGroupingFactor(2); // Group bits in pairs
/// // Ciphertexts and the key generation use the native modulus
/// let ciphertext_modulus = CiphertextModulus::new_native();
/// // The bootstrap key is then modulus switched to the modulus of the NTT, here the Goldilocks
/// // prime
/// let ntt_modulus = CiphertextModulus::try_new((1 << 64) - (1 << 32) + 1).unwrap();
///
/// // Request the best seeder possible, starting with hardware entropy sources and falling back to
/// // /dev/random on Unix systems if enabled via cargo features
/// let mut boxed_seeder = new_seeder();
/// // Get a mutable reference to the seeder as a trait object from the Box returned by new_seeder
/// let seeder = boxed_seeder.as_mut();
///
/// // Create a generator which uses a CSPRNG to generate secret keys
/// let mut secret_generator = SecretRandomGenerator::<DefaultRandomGenerator>::new(seeder.seed());
///
/// // Create a generator which uses two CSPRNGs to generate public masks and secret encryption
/// // noise
/// let mut encryption_generator =
///     EncryptionRandomGenerator::<DefaultRandomGenerator>::new(seeder.seed(), seeder);
///
/// println!("Generating keys...");
///
/// // Generate an LweSecretKey with binary coefficients
/// let small_lwe_sk =
///     LweSecretKey::generate_new_binary(small_lwe_dimension, &mut secret_generator);
///
/// // Generate a GlweSecretKey with binary coefficients
/// let glwe_sk =
///     GlweSecretKey::generate_new_binary(glwe_dimension, polynomial_size, &mut secret_generator);
///
/// // Create a copy of the GlweSecretKey re-interpreted as an LweSecretKey
/// let big_lwe_sk = glwe_sk.clone().into_lwe_secret_key();
///
/// let mut bsk = LweMultiBitBootstrapKey::new(
///     0u64,
///     glwe_dimension.to_glwe_size(),
///     polynomial_size,
///     pbs_base_log,
///     pbs_level,
///     small_lwe_dimension,
///     grouping_factor,
///     ciphertext_modulus,
/// );
///
/// par_generate_lwe_multi_bit_bootstrap_key(
///     &small_lwe_sk,
///     &glwe_sk,
///     &mut bsk,
///     glwe_noise_distribution,
///     &mut encryption_generator,
/// );
///
/// // Create the key that will hold the bootstrap key modulus switched to the NTT modulus, it
/// // stays in the standard domain
/// let mut ntt_modulus_bsk = LweMultiBitBootstrapKey::new(
///     0u64,
///     bsk.glwe_size(),
///     bsk.polynomial_size(),
///     bsk.decomposition_base_log(),
///     bsk.decomposition_level_count(),
///     bsk.input_lwe_dimension(),
///     bsk.grouping_factor(),
///     ntt_modulus,
/// );
///
/// modulus_switch_lwe_multi_bit_bootstrap_key_to_ntt64_modulus(&bsk, &mut ntt_modulus_bsk);
///
/// // We don't need the native modulus bootstrapping key anymore
/// drop(bsk);
///
/// // Our 4 bits message space
/// let message_modulus = 1u64 << 4;
///
/// // Our input message
/// let input_message = 3u64;
///
/// // Delta used to encode 4 bits of message + a bit of padding on u64
/// let delta = (1_u64 << 63) / message_modulus;
///
/// // Apply our encoding
/// let plaintext = Plaintext(input_message * delta);
///
/// // Allocate a new LweCiphertext and encrypt our plaintext
/// let lwe_ciphertext_in: LweCiphertextOwned<u64> = allocate_and_encrypt_new_lwe_ciphertext(
///     &small_lwe_sk,
///     plaintext,
///     lwe_noise_distribution,
///     ciphertext_modulus,
///     &mut encryption_generator,
/// );
///
/// // Now we will use a PBS to compute a multiplication by 2, it is NOT the recommended way of
/// // doing this operation in terms of performance as it's much more costly than a multiplication
/// // with a cleartext, however it resets the noise in a ciphertext to a nominal level and allows
/// // to evaluate arbitrary functions so depending on your use case it can be a better fit.
///
/// // Generate the accumulator for our multiplication by 2 using a simple closure
/// let accumulator: GlweCiphertextOwned<u64> = generate_programmable_bootstrap_glwe_lut(
///     polynomial_size,
///     glwe_dimension.to_glwe_size(),
///     message_modulus as usize,
///     ciphertext_modulus,
///     delta,
///     |x: u64| 2 * x,
/// );
///
/// // Allocate the LweCiphertext to store the result of the PBS
/// let mut pbs_multiplication_ct = LweCiphertext::new(
///     0u64,
///     big_lwe_sk.lwe_dimension().to_lwe_size(),
///     ciphertext_modulus,
/// );
/// println!("Computing PBS...");
/// // Use 4 threads to compute the multi-bit PBS
/// multi_bit_programmable_bootstrap_ntt64_bnf_lwe_ciphertext(
///     &lwe_ciphertext_in,
///     &mut pbs_multiplication_ct,
///     &accumulator,
///     &ntt_modulus_bsk,
///     ThreadCount(4),
///     true,
/// );
///
/// // Decrypt the PBS multiplication result
/// let pbs_multiplication_plaintext: Plaintext<u64> =
///     decrypt_lwe_ciphertext(&big_lwe_sk, &pbs_multiplication_ct);
///
/// // Round and remove our encoding
/// let pbs_multiplication_result: u64 = divide_round(pbs_multiplication_plaintext.0, delta);
///
/// println!("Checking result...");
/// assert_eq!(6, pbs_multiplication_result);
/// println!(
///     "Multiplication via PBS result is correct! Expected 6, got {pbs_multiplication_result}"
/// );
/// ```
pub fn multi_bit_programmable_bootstrap_ntt64_bnf_lwe_ciphertext<
    InputScalar,
    InputCont,
    OutputCont,
    AccCont,
    KeyCont,
>(
    input: &LweCiphertext<InputCont>,
    output: &mut LweCiphertext<OutputCont>,
    accumulator: &GlweCiphertext<AccCont>,
    multi_bit_bsk: &LweMultiBitBootstrapKey<KeyCont>,
    thread_count: ThreadCount,
    deterministic_execution: bool,
) where
    InputScalar: UnsignedInteger + CastInto<usize> + CastFrom<usize>,
    InputCont: Container<Element = InputScalar> + Sync,
    OutputCont: ContainerMut<Element = u64>,
    AccCont: Container<Element = u64>,
    KeyCont: Container<Element = u64> + Sync,
{
    assert_eq!(
        input.lwe_size().to_lwe_dimension(),
        multi_bit_bsk.input_lwe_dimension(),
        "Mismatched input LweDimension. LweCiphertext input LweDimension {:?}. \
        LweMultiBitBootstrapKey input LweDimension {:?}.",
        input.lwe_size().to_lwe_dimension(),
        multi_bit_bsk.input_lwe_dimension(),
    );

    assert_eq!(
        output.lwe_size().to_lwe_dimension(),
        multi_bit_bsk.output_lwe_dimension(),
        "Mismatched output LweDimension. LweCiphertext output LweDimension {:?}. \
        LweMultiBitBootstrapKey output LweDimension {:?}.",
        output.lwe_size().to_lwe_dimension(),
        multi_bit_bsk.output_lwe_dimension(),
    );

    assert_eq!(
        accumulator.glwe_size(),
        multi_bit_bsk.glwe_size(),
        "Mismatched GlweSize. Accumulator GlweSize {:?}. \
        LweMultiBitBootstrapKey GlweSize {:?}.",
        accumulator.glwe_size(),
        multi_bit_bsk.glwe_size(),
    );

    assert_eq!(
        accumulator.polynomial_size(),
        multi_bit_bsk.polynomial_size(),
        "Mismatched PolynomialSize. Accumulator PolynomialSize {:?}. \
        LweMultiBitBootstrapKey PolynomialSize {:?}.",
        accumulator.polynomial_size(),
        multi_bit_bsk.polynomial_size(),
    );

    assert_eq!(
        output.ciphertext_modulus(),
        accumulator.ciphertext_modulus(),
        "Mismatched CiphertextModulus between output ({:?}) and accumulator ({:?})",
        output.ciphertext_modulus(),
        accumulator.ciphertext_modulus(),
    );

    assert!(
        thread_count.0 != 0,
        "Got thread_count == 0, this is not supported"
    );

    let mut local_accumulator = GlweCiphertext::new(
        0u64,
        accumulator.glwe_size(),
        accumulator.polynomial_size(),
        accumulator.ciphertext_modulus(),
    );
    local_accumulator
        .as_mut()
        .copy_from_slice(accumulator.as_ref());

    let grouping_factor = multi_bit_bsk.grouping_factor();

    let lut_poly_size = accumulator.polynomial_size();

    let multi_bit_modulus_switched_input = StandardMultiBitModulusSwitchedCt {
        input: input.as_view(),
        grouping_factor,
        log_modulus: lut_poly_size.to_blind_rotation_input_modulus_log(),
    };

    multi_bit_ntt64_bnf_blind_rotate_assign(
        &multi_bit_modulus_switched_input,
        &mut local_accumulator,
        multi_bit_bsk,
        thread_count,
        deterministic_execution,
    );

    extract_lwe_sample_from_glwe_ciphertext(&local_accumulator, output, MonomialDegree(0));
}

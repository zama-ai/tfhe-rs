// ============================================================================
// Bit-wise regression ("golden values") test for the *classical* 128-bit GPU
// programmable bootstrap — the bootstrap noise squashing runs — under a
// saturating batch.
//
// This is the PBS128 counterpart of the 64-bit golden test in `super::pbs_golden`
// and follows the same recipe: a deterministically generated key, a
// deterministically encrypted input replicated across a batch, one batched
// bootstrap call, and a bit-for-bit comparison of every lane against committed
// reference data. Both sides of the bootstrap are committed here — the input
// ciphertexts *and* the output ciphertexts — so a failure immediately says
// whether the host-side key generation / encryption drifted or whether the GPU
// bootstrap itself changed.
//
// The whole thing is repeated for each message in [`GOLDEN_MESSAGES`]: the
// message drives the monomial rotation of the accumulator in the blind rotate,
// so different messages exercise genuinely different rotation offsets (including
// the largest one, next to the negacyclic wrap) rather than re-running the same
// offset with different data.
//
// This module exercises the golden data two ways:
//   * `test_regression_classical_pbs128_golden` — one batched call per golden message at a *random*
//     batch size, asserting the per-bootstrap output is independent of how many bootstraps share
//     the call;
//   * `test_parallel_streams_classical_pbs128_golden` — many concurrent streams, each a randomly
//     sized batch and each assigned a *different* golden message, asserting robustness under
//     parallel execution and catching cross-stream contamination of the per-message rotation.
//
// The whole pipeline (key generation, encryption and the bootstrap) is made
// fully deterministic by seeding the CSPRNGs from a fixed `Seed`; the random
// batch sizes are printed so any failure can be reproduced.
//
// The parameters are the production noise-squashing parameters, whose input LWE
// dimension comes from the classical compute parameters:
//   * squashing : NOISE_SQUASHING_PARAM_MESSAGE_2_CARRY_2_KS_PBS_TUNIFORM_2M128
//   * input     : PARAM_MESSAGE_2_CARRY_2_KS_PBS_TUNIFORM_2M128
//
// ON THE PBS FLAVOR: the classical PBS128 backend always selects the
// step-one/step-two implementation — `scratch_cuda_programmable_bootstrap_128_vector`
// pins `force_step_one_step_two = true`, bypassing the TBC and CG
// specializations — and with N = 2048, base_log = 24 and level_count = 3 the
// step one that runs is the register-based one
// (`device_programmable_bootstrap_step_one_128_regs`). That holds on H100 too,
// where TBC would otherwise be eligible, so this test always pins the
// step1/step2 flavor on that configuration: any change of flavor changes the
// output bits and fails the comparison below.
//
// The golden data lives in `pbs128_golden_data::pbs128_golden_v1` (one reference
// input and one reference output per golden message) and is (re)generated by the
// `generate_pbs128_golden` maintenance helper below — a plain (non `#[test]`)
// function; run it on an H100 (sm_90) to refresh the file, then commit the
// result.
//
// The GPU FFT is only bit-reproducible within a given GPU generation, so this
// only runs on compute capability 9.x (H100) or newer, exactly like the 64-bit
// PBS golden test.
//
// NOTE ON THE GOLDEN VALUES: every committed output limb ends in a run of zero
// bits (~38 to ~55 of them, ~44 typically), i.e. only the top ~84 bits of each
// 128-bit torus coefficient carry information. That is the bootstrap itself, not
// a truncation of this test: the 128-bit PBS runs on an f128 (double-double)
// FFT, and `add_to_torus_128` rebuilds each torus coefficient out of exactly two
// `double`s with `u128_from_torus_f128` — the fractional part is scaled by 2^128
// and reassembled as `f64_to_u128(hi) + f64_to_i128(lo)`. The finest increment
// that pair can express is the ulp of `lo`, and because the value being
// converted is the fractional part of an accumulator of magnitude ~2^20 rather
// than of a number in [0, 1), that increment lands around 2^44 — everything
// below it is exactly (and deterministically) zero. The CPU backend reconstructs
// the coefficient the same way, in `core_crypto::fft_impl::fft128`, so this is a
// property of the algorithm and not of the GPU. It is harmless here: the message
// delta is 2^123, some eighty bits above the rounding, and the decryption sanity
// check below confirms every golden output still decrypts exactly.
// ============================================================================

/// Fixed seed driving every deterministic CSPRNG in this module. Changing it
/// invalidates the committed golden data (regenerate with `generate_pbs128_golden`).
const GOLDEN_SEED: u128 = 0x0d1c_e5ed_1280_2048;

/// Batch size at which the committed golden data was captured by
/// `generate_pbs128_golden`. It sits above every size the tests draw, so each
/// run also proves the per-bootstrap output is batch-size independent. Only the
/// regeneration helper pays for it, so it can stay larger than what the tests
/// use; it just has to stay fixed for reproducible regeneration.
const BATCH_SIZE: usize = 32;

/// The messages that are encrypted, replicated across the batch and
/// bootstrapped — one golden input/output pair is committed per message. Any
/// value in `[0, message_modulus * carry_modulus)` works; these span the
/// blind-rotation space, with `15` sitting at the largest rotation the parameter
/// set allows (right next to the negacyclic wrap). They are encrypted in this
/// order from a single deterministic generator, so reordering or resizing this
/// array invalidates the committed golden data.
const GOLDEN_MESSAGES: [u64; 3] = [1, 7, 15];

/// Upper bound (inclusive) on the random batch size used by the single-stream
/// random-batch regression test. A 128-bit bootstrap is far more expensive than
/// a 64-bit one — it runs two kernels per LWE dimension over a double-double
/// FFT — so this range stays small where the 64-bit golden test can afford
/// hundreds of lanes. It is bounded by [`BATCH_SIZE`], so every run still checks
/// the golden ciphertext against a batch size it was not captured at.
const MAX_REGRESSION_BATCH_SIZE: usize = 16;

/// Number of concurrent worker threads (each with its own CUDA stream) driven by
/// the parallel-execution stress test.
const NUM_PARALLEL_STREAMS: usize = 16;

/// Upper bound (inclusive) on the per-thread random batch size in the parallel
/// stress test. Kept below [`MAX_REGRESSION_BATCH_SIZE`] so no single thread
/// saturates the GPU on its own, letting more of the streams actually overlap
/// and stressing concurrent execution harder. The lower bound is 1: a zero-size
/// batch launches no kernel (an idle thread that would exercise nothing), so it
/// is excluded.
const MAX_PARALLEL_BATCH_SIZE: usize = 8;

/// The golden data was captured on an H100 and the GPU FFT is only guaranteed
/// bit-reproducible within a GPU generation, so these tests only run on Hopper
/// (compute capability 9.x) and newer.
///
/// NOTE: this reuses the FFT16x4x16 capability probe, which is implemented in
/// the CUDA backend as a pure `prop.major >= 9` (Hopper / H100+) device query.
fn hopper_or_newer_is_supported() -> bool {
    // Safe: a pure runtime device-capability query with no aliasing concerns.
    unsafe { cuda_fft16x4x16_is_supported_async(0) }
}

/// Builds the deterministic secret- and encryption-random generators used to
/// generate keys and encrypt inputs, seeded from [`GOLDEN_SEED`]. The seed
/// consumption order matches [`TestResources::new`] so the two stay comparable.
fn deterministic_generators() -> (
    SecretRandomGenerator<DefaultRandomGenerator>,
    EncryptionRandomGenerator<DefaultRandomGenerator>,
) {
    let mut deterministic_seeder =
        DeterministicSeeder::<DefaultRandomGenerator>::new(Seed(GOLDEN_SEED));
    let encryption_random_generator = EncryptionRandomGenerator::<DefaultRandomGenerator>::new(
        deterministic_seeder.seed(),
        &mut deterministic_seeder,
    );
    let secret_random_generator =
        SecretRandomGenerator::<DefaultRandomGenerator>::new(deterministic_seeder.seed());
    (secret_random_generator, encryption_random_generator)
}

/// Replicates one input LWE ciphertext into a device list of `batch_size`
/// identical copies.
fn replicated_input(
    lwe_ciphertext_in: &LweCiphertextOwned<u64>,
    stream: &CudaStreams,
    batch_size: usize,
) -> CudaLweCiphertextList<u64> {
    let lwe_size = lwe_ciphertext_in.lwe_size();
    let mut container = Vec::with_capacity(lwe_size.0 * batch_size);
    for _ in 0..batch_size {
        container.extend_from_slice(lwe_ciphertext_in.as_ref());
    }
    let h_input = LweCiphertextList::from_container(
        container,
        lwe_size,
        lwe_ciphertext_in.ciphertext_modulus(),
    );
    CudaLweCiphertextList::from_lwe_ciphertext_list(&h_input, stream)
}

/// Everything the golden runs share: the deterministic key material (device
/// bootstrap key plus the output secret key used by the correctness sanity
/// check), the accumulator and the deterministically encrypted golden inputs.
/// Building it is by far the most expensive part of the test, so it is built
/// once per test and reused by every batched run.
struct Pbs128GoldenSetup {
    /// Owns the stream the bootstrap key and accumulator were uploaded on; it
    /// must outlive them, and it is also the stream the single-threaded runs use.
    stream: CudaStreams,
    d_bsk: CudaLweBootstrapKey,
    d_accumulator: CudaGlweCiphertextList<u128>,
    output_lwe_secret_key: LweSecretKeyOwned<u128>,
    output_lwe_dimension: LweDimension,
    /// One deterministically encrypted input per message of [`GOLDEN_MESSAGES`].
    inputs: Vec<LweCiphertextOwned<u64>>,
    ciphertext_modulus: CiphertextModulus<u128>,
    /// Plaintext scaling of the 128-bit output space.
    delta: u128,
    /// Full plaintext space of the parameter set (message * carry).
    msg_modulus: u128,
}

/// The LUT the golden runs bootstrap with. Kept as a free function so the
/// accumulator and the correctness sanity check cannot drift apart.
fn golden_lut(msg_modulus: u128) -> impl Fn(u128) -> u128 {
    move |x: u128| x.wrapping_mul(2).wrapping_sub(1).wrapping_rem(msg_modulus)
}

/// Deterministically generates the noise-squashing key material and encrypts
/// every message of [`GOLDEN_MESSAGES`], in order, from a single seeded pair of
/// generators. The generation and encryption order fixes the generators' state,
/// so it must stay identical between the regression runs and
/// `generate_pbs128_golden` or the committed golden data no longer matches.
fn setup_pbs128_golden(
    squash_params: NoiseSquashingClassicParameters,
    input_params: ClassicPBSParameters,
) -> Pbs128GoldenSetup {
    let input_lwe_dimension = input_params.lwe_dimension;
    let lwe_noise_distribution = input_params.lwe_noise_distribution;
    let input_ciphertext_modulus = input_params.ciphertext_modulus;
    let glwe_noise_distribution = squash_params.glwe_noise_distribution;
    let ciphertext_modulus = squash_params.ciphertext_modulus;
    let glwe_dimension = squash_params.glwe_dimension;
    let polynomial_size = squash_params.polynomial_size;
    let decomp_base_log = squash_params.decomp_base_log;
    let decomp_level_count = squash_params.decomp_level_count;
    // Full plaintext space of the parameter set (message * carry).
    let msg_modulus = (squash_params.message_modulus.0 * squash_params.carry_modulus.0) as u128;

    let stream = CudaStreams::new_single_gpu(GpuIndex::new(0));

    let (mut secret_random_generator, mut encryption_random_generator) = deterministic_generators();

    let delta = get_encoding_with_padding(ciphertext_modulus) / msg_modulus;
    let delta_in = get_encoding_with_padding(input_ciphertext_modulus) / msg_modulus as u64;

    let accumulator = generate_programmable_bootstrap_glwe_lut(
        polynomial_size,
        glwe_dimension.to_glwe_size(),
        msg_modulus as usize,
        ciphertext_modulus,
        delta,
        golden_lut(msg_modulus),
    );

    // The input of the noise-squashing bootstrap is a 64-bit ciphertext, the
    // output a 128-bit one, so the two secret keys live in different domains.
    let input_lwe_secret_key = allocate_and_generate_new_binary_lwe_secret_key::<u64, _>(
        input_lwe_dimension,
        &mut secret_random_generator,
    );
    let output_glwe_secret_key = allocate_and_generate_new_binary_glwe_secret_key::<u128, _>(
        glwe_dimension,
        polynomial_size,
        &mut secret_random_generator,
    );
    let output_lwe_secret_key = output_glwe_secret_key.clone().into_lwe_secret_key();
    let output_lwe_dimension = output_lwe_secret_key.lwe_dimension();

    let mut bsk = LweBootstrapKey::new(
        0u128,
        glwe_dimension.to_glwe_size(),
        polynomial_size,
        decomp_base_log,
        decomp_level_count,
        input_lwe_dimension,
        ciphertext_modulus,
    );
    par_generate_lwe_bootstrap_key(
        &input_lwe_secret_key,
        &output_glwe_secret_key,
        &mut bsk,
        glwe_noise_distribution,
        &mut encryption_random_generator,
    );

    let modulus_switch_noise_reduction_configuration =
        match squash_params.modulus_switch_noise_reduction_params {
            ModulusSwitchType::Standard => None,
            ModulusSwitchType::DriftTechniqueNoiseReduction(_) => {
                panic!("Drift noise reduction is not supported on GPU")
            }
            ModulusSwitchType::CenteredMeanNoiseReduction => {
                Some(CudaModulusSwitchNoiseReductionConfiguration::Centered)
            }
        };
    let d_bsk = CudaLweBootstrapKey::from_lwe_bootstrap_key(
        &bsk,
        modulus_switch_noise_reduction_configuration,
        &stream,
    );

    let inputs = GOLDEN_MESSAGES
        .iter()
        .map(|&message| {
            allocate_and_encrypt_new_lwe_ciphertext(
                &input_lwe_secret_key,
                Plaintext(message * delta_in),
                lwe_noise_distribution,
                input_ciphertext_modulus,
                &mut encryption_random_generator,
            )
        })
        .collect();

    // The accumulator does not depend on the message, so it is uploaded once and
    // reused (read-only) by every run, including the concurrent ones.
    let d_accumulator = CudaGlweCiphertextList::from_glwe_ciphertext(&accumulator, &stream);

    Pbs128GoldenSetup {
        stream,
        d_bsk,
        d_accumulator,
        output_lwe_secret_key,
        output_lwe_dimension,
        inputs,
        ciphertext_modulus,
        delta,
        msg_modulus,
    }
}

impl Pbs128GoldenSetup {
    /// Decrypts one output ciphertext and checks it against the LUT applied to
    /// `message`, so a frozen golden output is always also a *correct* PBS
    /// result and we never enshrine garbage as golden data.
    fn assert_decrypts_to_lut(&self, output: &LweCiphertext<&[u128]>, message: u64) {
        let decrypted = decrypt_lwe_ciphertext(&self.output_lwe_secret_key, output);
        let decoded = round_decode(decrypted.0, self.delta) % self.msg_modulus;
        assert_eq!(
            decoded,
            golden_lut(self.msg_modulus)(message as u128),
            "classical GPU PBS128 produced an incorrect result for msg={message}"
        );
    }

    /// Allocates the 128-bit output list of a `batch_size` batched bootstrap.
    fn new_output(&self, stream: &CudaStreams, batch_size: usize) -> CudaLweCiphertextList<u128> {
        CudaLweCiphertextList::new(
            self.output_lwe_dimension,
            LweCiphertextCount(batch_size),
            self.ciphertext_modulus,
            stream,
        )
    }
}

/// Runs the classical 128-bit GPU PBS on a batch of `batch_size` identical
/// inputs, once per message of [`GOLDEN_MESSAGES`], and returns the raw output
/// ciphertext limbs (mask followed by body) of every lane, indexed by message
/// then by lane.
fn run_pbs128_golden_batch(setup: &Pbs128GoldenSetup, batch_size: usize) -> Vec<Vec<Vec<u128>>> {
    let stream = &setup.stream;
    let mut d_output = setup.new_output(stream, batch_size);

    let mut per_message = Vec::with_capacity(GOLDEN_MESSAGES.len());
    for (&message, lwe_ciphertext_in) in GOLDEN_MESSAGES.iter().zip(&setup.inputs) {
        let d_input = replicated_input(lwe_ciphertext_in, stream, batch_size);

        cuda_programmable_bootstrap_128_lwe_ciphertext(
            &d_input,
            &mut d_output,
            &setup.d_accumulator,
            &setup.d_bsk,
            stream,
        );

        let out_host = d_output.to_lwe_ciphertext_list(stream);

        // Sanity check on the first lane before freezing anything as golden.
        setup.assert_decrypts_to_lut(&out_host.iter().next().unwrap(), message);

        per_message.push(out_host.iter().map(|ct| ct.as_ref().to_vec()).collect());
    }

    per_message
}

/// Compares one ciphertext against its golden reference limb by limb, reporting
/// only the first mismatch. A ciphertext here is thousands of limbs wide, so a
/// plain `assert_eq!` on the two slices would bury the failure under a dump of
/// the whole pair.
fn assert_limbs_match<T: PartialEq + std::fmt::LowerHex>(
    actual: &[T],
    expected: &[T],
    label: &str,
) {
    assert_eq!(
        actual.len(),
        expected.len(),
        "{label}: got {} limbs but the golden data holds {}; regenerate it with \
         `generate_pbs128_golden` after changing the parameters",
        actual.len(),
        expected.len()
    );
    if let Some((limb, (got, want))) = actual
        .iter()
        .zip(expected)
        .enumerate()
        .find(|(_, (got, want))| got != want)
    {
        panic!(
            "{label}: limb {limb}/{} does not match the golden data: got {got:#x}, \
             expected {want:#x}",
            actual.len()
        );
    }
}

/// Asserts every lane of a batched run reproduces `expected`, bit for bit.
fn assert_all_lanes_match(batch: &[Vec<u128>], expected: &[u128], label: &str) {
    let batch_size = batch.len();
    assert!(batch_size > 0, "{label}: empty batch");
    for (lane, ct) in batch.iter().enumerate() {
        assert_limbs_match(
            ct,
            expected,
            &format!("{label}: batched GPU PBS128 lane {lane}/{batch_size}"),
        );
    }
}

/// Asserts every message's batch reproduces the golden ciphertext committed for
/// that message. Every golden message is checked on every run: a bit-exactness
/// regression is a hard gate, so its coverage must not be sampled.
fn assert_all_messages_match(batches: &[Vec<Vec<u128>>], expected: &[&[u128]], label: &str) {
    assert_eq!(
        batches.len(),
        expected.len(),
        "{label}: ran {} messages but the golden data holds {}; regenerate it \
         with `generate_pbs128_golden` after changing GOLDEN_MESSAGES",
        batches.len(),
        expected.len()
    );
    for ((&message, batch), golden) in GOLDEN_MESSAGES.iter().zip(batches).zip(expected) {
        assert_all_lanes_match(batch, golden, &format!("{label} msg={message}"));
    }
}

/// Asserts the deterministically generated key material and encryption still
/// produce the committed golden *input* ciphertexts. This runs before the output
/// comparison so a host-side drift (key generation, encryption, seeding order)
/// is reported as such instead of surfacing as a bogus GPU regression.
fn assert_inputs_match(setup: &Pbs128GoldenSetup, label: &str) {
    assert_eq!(
        setup.inputs.len(),
        CLASSICAL_INPUT_EXPECTED.len(),
        "{label}: encrypted {} inputs but the golden data holds {}; regenerate it \
         with `generate_pbs128_golden` after changing GOLDEN_MESSAGES",
        setup.inputs.len(),
        CLASSICAL_INPUT_EXPECTED.len()
    );
    for ((&message, input), golden) in GOLDEN_MESSAGES
        .iter()
        .zip(&setup.inputs)
        .zip(CLASSICAL_INPUT_EXPECTED)
    {
        assert_limbs_match(
            input.as_ref(),
            golden,
            &format!(
                "{label} msg={message}: the deterministically encrypted input does not match \
                 the golden input (the host-side key generation or encryption changed, so the \
                 golden output data cannot be checked)"
            ),
        );
    }
}

/// The classical noise-squashing parameters used by every test here, unwrapped
/// from the [`NoiseSquashingParameters`] enum.
fn golden_squashing_params() -> NoiseSquashingClassicParameters {
    let NoiseSquashingParameters::Classic(squash_params) =
        NOISE_SQUASHING_PARAM_MESSAGE_2_CARRY_2_KS_PBS_TUNIFORM_2M128
    else {
        panic!("Multi bit noise squashing PBS currently not supported on GPU");
    };
    squash_params
}

#[test]
fn test_regression_classical_pbs128_golden() {
    if !hopper_or_newer_is_supported() {
        println!(
            "skipping test_regression_classical_pbs128_golden: the PBS128 golden data \
             requires compute capability 9.x (H100) or newer"
        );
        return;
    }

    // Random batch size: the golden output is per-bootstrap and must not depend
    // on how many bootstraps share the batched call. The size is printed so a
    // failure can be reproduced deterministically.
    let batch_size = rand::thread_rng().gen_range(1..=MAX_REGRESSION_BATCH_SIZE);
    println!("test_regression_classical_pbs128_golden: batch size {batch_size}");

    let label = "NOISE_SQUASHING_PARAM_MESSAGE_2_CARRY_2_KS_PBS_TUNIFORM_2M128";
    let setup = setup_pbs128_golden(
        golden_squashing_params(),
        PARAM_MESSAGE_2_CARRY_2_KS_PBS_TUNIFORM_2M128,
    );
    assert_inputs_match(&setup, label);

    let batches = run_pbs128_golden_batch(&setup, batch_size);
    assert_all_messages_match(&batches, CLASSICAL_OUTPUT_EXPECTED, label);
}

// ============================================================================
// Parallel-execution robustness stress test.
//
// Where the test above validates a single batched call, this drives
// `NUM_PARALLEL_STREAMS` worker threads *concurrently*, each on its own CUDA
// stream, each launching a batch of a random size in
// `[1, MAX_PARALLEL_BATCH_SIZE]`. Threads are assigned golden messages round
// robin, so concurrent streams bootstrap *different* inputs against the shared
// bootstrap key and accumulator; every output lane must still reproduce the
// golden ciphertext committed for that thread's message, bit for bit. This
// catches races, per-stream state leakage and scheduling-dependent
// non-determinism that a single-stream run cannot — and, because neighbouring
// streams now rotate the accumulator by different amounts, cross-stream
// contamination that identical inputs would mask.
//
// The whole setup (keys, encrypted golden inputs, per-thread device buffers and
// the random batch sizes) is built in a preprocessing phase and fully
// materialized (`cuda_synchronize_device`) *before* any thread launches, so the
// parallel section contains only the concurrent bootstrap launches.
// ============================================================================

/// What one worker thread was asked to run. Kept separately from the device
/// buffers so the assertions can still name the thread's batch size and message
/// after [`ThreadWork`] has been consumed.
#[derive(Clone, Copy)]
struct ThreadSpec {
    batch_size: usize,
    /// Index into [`GOLDEN_MESSAGES`] — selects both the thread's input
    /// ciphertext and the golden block its output must match.
    msg_idx: usize,
}

/// Per-thread device-side work prepared during preprocessing: an owned stream
/// plus the batched input and output buffers sized for that thread's randomly
/// chosen batch size. The bootstrap key and accumulator are shared read-only
/// across all threads, so they are deliberately *not* stored here.
struct ThreadWork {
    stream: CudaStreams,
    spec: ThreadSpec,
    d_input: CudaLweCiphertextList<u64>,
    d_output: CudaLweCiphertextList<u128>,
}

/// Preprocessing phase: allocates one stream per worker thread and builds, on
/// that stream, the replicated golden input and output buffers for a random
/// batch size in `[1, MAX_PARALLEL_BATCH_SIZE]`. Threads take their input from
/// the setup round robin, so concurrent streams run different golden messages.
/// All device work is synchronized before returning, so the caller can launch
/// every thread's bootstrap in parallel with no outstanding transfers.
fn preprocess_thread_work(setup: &Pbs128GoldenSetup) -> Vec<ThreadWork> {
    let mut rng = rand::thread_rng();
    let work: Vec<ThreadWork> = (0..NUM_PARALLEL_STREAMS)
        .map(|thread| {
            let batch_size = rng.gen_range(1..=MAX_PARALLEL_BATCH_SIZE);
            let msg_idx = thread % setup.inputs.len();
            let stream = CudaStreams::new_single_gpu(GpuIndex::new(0));

            let d_input = replicated_input(&setup.inputs[msg_idx], &stream, batch_size);
            let d_output = setup.new_output(&stream, batch_size);

            ThreadWork {
                stream,
                spec: ThreadSpec {
                    batch_size,
                    msg_idx,
                },
                d_input,
                d_output,
            }
        })
        .collect();

    // Materialize every preprocessing transfer before the parallel phase so no
    // thread races an in-flight upload on another stream.
    unsafe { cuda_synchronize_device(0) };

    println!(
        "parallel PBS128 stress: {NUM_PARALLEL_STREAMS} streams, (batch size, msg) {:?}",
        work.iter()
            .map(|w| (w.spec.batch_size, GOLDEN_MESSAGES[w.spec.msg_idx]))
            .collect::<Vec<_>>()
    );

    work
}

/// Launches every thread's bootstrap concurrently (one OS thread per stream via
/// `std::thread::scope`), waits for all of them, and returns each thread's raw
/// per-lane output ciphertext limbs. The bootstrap key and accumulator are only
/// ever read, so sharing them across the threads is sound.
fn spawn_and_collect(setup: &Pbs128GoldenSetup, work: &mut [ThreadWork]) -> Vec<Vec<Vec<u128>>> {
    std::thread::scope(|scope| {
        let handles: Vec<_> = work
            .iter_mut()
            .map(|w| {
                scope.spawn(move || {
                    cuda_programmable_bootstrap_128_lwe_ciphertext(
                        &w.d_input,
                        &mut w.d_output,
                        &setup.d_accumulator,
                        &setup.d_bsk,
                        &w.stream,
                    );
                    let out_host = w.d_output.to_lwe_ciphertext_list(&w.stream);
                    out_host
                        .iter()
                        .map(|ct| ct.as_ref().to_vec())
                        .collect::<Vec<Vec<u128>>>()
                })
            })
            .collect();

        handles
            .into_iter()
            .map(|h| h.join().expect("parallel PBS128 worker thread panicked"))
            .collect()
    })
}

/// Asserts every lane produced by every thread reproduces the golden ciphertext
/// committed for that thread's message, bit for bit, and that each thread
/// produced exactly its requested batch size.
fn assert_all_threads_match(
    results: &[Vec<Vec<u128>>],
    specs: &[ThreadSpec],
    expected: &[&[u128]],
    label: &str,
) {
    for (thread, (lanes, spec)) in results.iter().zip(specs).enumerate() {
        let ThreadSpec {
            batch_size,
            msg_idx,
        } = *spec;
        let message = GOLDEN_MESSAGES[msg_idx];
        assert_eq!(
            lanes.len(),
            batch_size,
            "{label}: thread {thread} produced {} lanes, expected {batch_size}",
            lanes.len()
        );
        for (lane, ct) in lanes.iter().enumerate() {
            assert_limbs_match(
                ct,
                expected[msg_idx],
                &format!("{label} msg={message}: thread {thread} lane {lane}/{batch_size}"),
            );
        }
    }
}

#[test]
fn test_parallel_streams_classical_pbs128_golden() {
    if !hopper_or_newer_is_supported() {
        println!(
            "skipping test_parallel_streams_classical_pbs128_golden: the PBS128 golden \
             data requires compute capability 9.x (H100) or newer"
        );
        return;
    }

    let label = "NOISE_SQUASHING_PARAM_MESSAGE_2_CARRY_2_KS_PBS_TUNIFORM_2M128";
    let setup = setup_pbs128_golden(
        golden_squashing_params(),
        PARAM_MESSAGE_2_CARRY_2_KS_PBS_TUNIFORM_2M128,
    );
    assert_inputs_match(&setup, label);

    // The bootstrap key and accumulator uploads must be complete before the
    // worker threads start reading them from their own streams.
    unsafe { cuda_synchronize_device(0) };

    let mut work = preprocess_thread_work(&setup);
    let specs: Vec<ThreadSpec> = work.iter().map(|w| w.spec).collect();

    let results = spawn_and_collect(&setup, &mut work);
    assert_all_threads_match(&results, &specs, CLASSICAL_OUTPUT_EXPECTED, label);
}

/// Formats a `pub const <name>: &[&[$ty]] = &[...]` block holding one inner
/// slice of hex limbs per message of [`GOLDEN_MESSAGES`], in the same order.
/// `width` is the `{:#0width$x}` width of one limb (18 for `u64`, 34 for `u128`).
fn format_golden_const<T: std::fmt::LowerHex>(
    name: &str,
    ty: &str,
    width: usize,
    per_message: &[Vec<T>],
) -> String {
    let mut body = String::new();
    for (values, message) in per_message.iter().zip(GOLDEN_MESSAGES) {
        let _ = writeln!(body, "    // msg = {message}");
        let _ = writeln!(body, "    &[");
        for v in values {
            let _ = writeln!(body, "        {v:#0width$x},");
        }
        let _ = writeln!(body, "    ],");
    }
    format!("pub const {name}: &[&[{ty}]] = &[\n{body}];\n\n")
}

/// Asserts every lane of each message's batched run agrees, and returns that
/// message's lane 0 as its golden reference ciphertext.
fn golden_from_batches(batches: &[Vec<Vec<u128>>], label: &str) -> Vec<Vec<u128>> {
    batches
        .iter()
        .zip(GOLDEN_MESSAGES)
        .map(|(batch, message)| {
            let reference = batch[0].clone();
            assert_all_lanes_match(batch, &reference, &format!("{label} msg={message}"));
            reference
        })
        .collect()
}

/// (Re)generates the PBS128 golden file. This is *not* a test — it is a manual
/// maintenance helper. To refresh the golden data, temporarily annotate it with
/// `#[test]` `#[ignore]`, run it on an H100 (sm_90) with
/// `cargo test ... -- --ignored --exact`, then commit the regenerated file and
/// remove the annotations again.
#[allow(dead_code)]
fn generate_pbs128_golden() {
    if !hopper_or_newer_is_supported() {
        println!(
            "skipping generate_pbs128_golden: the PBS128 golden data requires compute \
             capability 9.x (H100) or newer"
        );
        return;
    }

    let setup = setup_pbs128_golden(
        golden_squashing_params(),
        PARAM_MESSAGE_2_CARRY_2_KS_PBS_TUNIFORM_2M128,
    );
    let inputs: Vec<Vec<u64>> = setup.inputs.iter().map(|ct| ct.as_ref().to_vec()).collect();
    let outputs = golden_from_batches(
        &run_pbs128_golden_batch(&setup, BATCH_SIZE),
        "classical_pbs128",
    );

    let mut contents = String::from(
        "// @generated by the `generate_pbs128_golden` helper in\n\
         // core_crypto::gpu::algorithms::test::pbs128_golden. Do not edit by hand.\n",
    );
    contents += &format_golden_const("CLASSICAL_INPUT_EXPECTED", "u64", 18, &inputs);
    contents += &format_golden_const("CLASSICAL_OUTPUT_EXPECTED", "u128", 34, &outputs);

    // Normalize to a single trailing newline so the generated file is
    // rustfmt-stable and needs no manual formatting pass after regeneration.
    let contents = format!("{}\n", contents.trim_end());

    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/src/core_crypto/gpu/algorithms/test/pbs128_golden/pbs128_golden_data/pbs128_golden_v1.rs"
    );
    std::fs::write(path, contents).expect("failed to write PBS128 golden file");
    println!("wrote PBS128 golden data to {path}");
}
